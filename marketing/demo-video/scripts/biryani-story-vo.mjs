// First-person VO for the "Biryani night" story film, with word timings.
//   ELEVENLABS_API_KEY=... node scripts/biryani-story-vo.mjs [model]
import fs from 'node:fs';

const KEY = process.env.ELEVENLABS_API_KEY;
if (!KEY) throw new Error('ELEVENLABS_API_KEY missing');
const VOICE = 'cgSgspJ2msm6clMCkdW9'; // Jessica - Playful, Bright, Warm (premade; library voices need a paid API plan)
const MODEL = process.argv[2] || 'eleven_v3';
const TEXT = MODEL === 'eleven_v3'
	? "[sighs] Okay. Friday night. I promised everyone biryani... and I have never made biryani. [laughs softly] So I held Control and Option, and just asked. How do I cook chicken biryani? And it didn't give me an essay. It drew it. Right on my screen. Marinate. Boil. Fry. Layer. [excited] Honestly? Best one I've ever made. Ask about anything on your screen. HeyMate. Free, for your Mac."
	: "Okay. Friday night. I promised everyone biryani... and I have never made biryani. So I held Control and Option, and just asked. How do I cook chicken biryani? And it didn't give me an essay. It drew it. Right on my screen. Marinate. Boil. Fry. Layer. Honestly? Best one I've ever made. Ask about anything on your screen. HeyMate. Free, for your Mac.";

const res = await fetch(`https://api.elevenlabs.io/v1/text-to-speech/${VOICE}/with-timestamps?output_format=mp3_44100_128`, {
	method: 'POST',
	headers: {'xi-api-key': KEY, 'content-type': 'application/json'},
	body: JSON.stringify({text: TEXT, model_id: MODEL, voice_settings: {stability: 0.5, similarity_boost: 0.8, style: 0.4, use_speaker_boost: true}}),
});
if (!res.ok) throw new Error(`ElevenLabs ${res.status}: ${(await res.text()).slice(0, 300)}`);
const json = await res.json();
fs.writeFileSync('public/biryani-story/vo.mp3', Buffer.from(json.audio_base64, 'base64'));
const {characters: ch, character_start_times_seconds: st, character_end_times_seconds: en} = json.alignment;
const words = [];
let cur = null;
ch.forEach((c, i) => {
	if (/\s/.test(c)) { if (cur) words.push(cur); cur = null; }
	else if (!cur) cur = {w: c, start: st[i], end: en[i]};
	else { cur.w += c; cur.end = en[i]; }
});
if (cur) words.push(cur);
const spoken = words.filter((w) => !/^\[|\]$/.test(w.w));
fs.writeFileSync('src/biryani-story/voWords.ts', `// Generated by scripts/biryani-story-vo.mjs\nexport const VO_WORDS = ${JSON.stringify(spoken.map((w) => ({...w, start: +w.start.toFixed(3), end: +w.end.toFixed(3)})))} as const;\n`);
console.log(spoken.map((w) => `${w.start.toFixed(2)} ${w.w}`).join(' | '));

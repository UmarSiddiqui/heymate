// ElevenLabs VO for the "Ask. It draws." film, with word timings.
// ELEVENLABS_API_KEY from env (never written to disk); voice ID from ~/.config/heymate/secrets.env.
//   ELEVENLABS_API_KEY=... node scripts/askdraws-vo.mjs
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const env = Object.fromEntries(fs.readFileSync(path.join(os.homedir(), '.config/heymate/secrets.env'), 'utf8').split('\n').map((l) => l.match(/^\s*([A-Z0-9_]+)=["']?(.*?)["']?\s*$/)).filter(Boolean).map((m) => [m[1], m[2]]));
const KEY = process.env.ELEVENLABS_API_KEY;
const VOICE = env.ELEVENLABS_VOICE_ID;
if (!KEY || !VOICE) throw new Error('ELEVENLABS_API_KEY / ELEVENLABS_VOICE_ID missing');

const TEXT = "You've got a question. About what's on your screen. Hold Control and Option... and just ask. HeyMate doesn't hand you a wall of text. It draws the answer. Step by step. Right where you're looking. A recipe becomes a plan. A circuit board becomes a map. And when flat isn't enough... it goes 3D. Ask about anything on your screen. HeyMate. Free and open source. For your Mac.";

const res = await fetch(`https://api.elevenlabs.io/v1/text-to-speech/${VOICE}/with-timestamps?output_format=mp3_44100_128`, {
	method: 'POST',
	headers: {'xi-api-key': KEY, 'content-type': 'application/json'},
	body: JSON.stringify({text: TEXT, model_id: 'eleven_multilingual_v2', voice_settings: {stability: 0.5, similarity_boost: 0.8, style: 0.3, use_speaker_boost: true, speed: 0.96}}),
});
if (!res.ok) throw new Error(`ElevenLabs ${res.status}: ${(await res.text()).slice(0, 300)}`);
const json = await res.json();
fs.writeFileSync('public/askdraws/vo.mp3', Buffer.from(json.audio_base64, 'base64'));
const {characters: ch, character_start_times_seconds: st, character_end_times_seconds: en} = json.alignment;
const words = [];
let cur = null;
ch.forEach((c, i) => {
	if (/\s/.test(c)) { if (cur) words.push(cur); cur = null; }
	else if (!cur) cur = {w: c, start: st[i], end: en[i]};
	else { cur.w += c; cur.end = en[i]; }
});
if (cur) words.push(cur);
fs.writeFileSync('src/askdraws/voWords.ts', `// Generated by scripts/askdraws-vo.mjs\nexport const VO_WORDS = ${JSON.stringify(words.map((w) => ({...w, start: +w.start.toFixed(3), end: +w.end.toFixed(3)})))} as const;\n`);
console.log(words.map((w) => `${w.start.toFixed(2)} ${w.w}`).join('\n'));

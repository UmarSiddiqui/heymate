// Builds HeyMate/mate-three.js from entry.mjs and the pinned three.js in package-lock.json.
//   node build.mjs           write the bundle
//   node build.mjs --check   fail if the committed bundle differs from a fresh build
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const here = new URL('./', import.meta.url);
const out = new URL('../../HeyMate/mate-three.js', import.meta.url);
const three = JSON.parse(readFileSync(new URL('node_modules/three/package.json', here)));
const esbuild = JSON.parse(readFileSync(new URL('node_modules/esbuild/package.json', here)));

const result = await build({
  entryPoints: [new URL('entry.mjs', here).pathname],
  bundle: true,
  format: 'iife',
  globalName: 'MateThreeLib',
  platform: 'neutral',
  // three's source modules rather than its prebuilt files: the addons' `import 'three'` would otherwise pull in the
  // whole WebGL renderer, and per-class modules let unused classes drop out.
  plugins: [{
    name: 'three-core-source',
    setup(b) { b.onResolve({ filter: /^three$/ }, () => ({ path: new URL('node_modules/three/src/Three.Core.js', here).pathname })); },
  }],
  target: 'safari17',            // WKWebView on macOS 14.2, HeyMate's oldest supported system
  minify: true,
  legalComments: 'none',         // the notice is in the header below
  charset: 'utf8',
  write: false,
  logLevel: 'warning',
});
const body = result.outputFiles[0].text;
const header = [
  `// three.js ${three.version} (MIT License, Copyright 2010-2026 three.js authors, https://threejs.org).`,
  '// Generated by scripts/three-kernel/build.mjs from scripts/three-kernel/entry.mjs; do not edit by hand.',
  `// esbuild ${esbuild.version}. Defines globalThis.MateThreeLib. Body sha256 ${createHash('sha256').update(body).digest('hex')}.`,
  '',
].join('\n');
const bundle = header + body;

if (process.argv.includes('--check')) {
  if (readFileSync(out, 'utf8') !== bundle) {
    console.error('HeyMate/mate-three.js differs from a fresh build; run `npm run build` in scripts/three-kernel.');
    process.exit(1);
  }
  console.log('mate-three.js matches its build');
} else {
  writeFileSync(out, bundle);
  console.log(`wrote mate-three.js: ${bundle.length} bytes, three.js ${three.version}`);
}

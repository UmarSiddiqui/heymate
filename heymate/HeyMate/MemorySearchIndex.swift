import Foundation
import SQLite3

/// A disposable index of already-scoped text. JSON remains authoritative.
/// In-memory SQLite avoids a second on-disk copy or stale deleted embeddings.
nonisolated final class MemorySearchIndex {
    private var database: OpaquePointer?
    private enum IndexError: Error { case unavailable }
    private let transient = unsafeBitCast(-1, to: sqlite3_destructor_type.self)

    init(items: [MemoryItem]) throws {
        guard sqlite3_open(":memory:", &database) == SQLITE_OK, let database else {
            if let database { sqlite3_close(database) }
            self.database = nil
            throw IndexError.unavailable
        }
        guard sqlite3_exec(database, "PRAGMA temp_store=MEMORY", nil, nil, nil) == SQLITE_OK,
              sqlite3_exec(database, "CREATE VIRTUAL TABLE memories USING fts5(id UNINDEXED, body, tokenize='porter unicode61 remove_diacritics 2')", nil, nil, nil) == SQLITE_OK else {
            sqlite3_close(database)
            self.database = nil
            throw IndexError.unavailable
        }
        var statement: OpaquePointer?
        guard sqlite3_prepare_v2(database, "INSERT INTO memories(id,body) VALUES (?,?)", -1, &statement, nil) == SQLITE_OK else {
            sqlite3_close(database)
            self.database = nil
            throw IndexError.unavailable
        }
        defer { sqlite3_finalize(statement) }
        for item in items {
            sqlite3_reset(statement)
            sqlite3_clear_bindings(statement)
            sqlite3_bind_text(statement, 1, item.id.uuidString, -1, transient)
            sqlite3_bind_text(statement, 2, item.text, -1, transient)
            guard sqlite3_step(statement) == SQLITE_DONE else { throw IndexError.unavailable }
        }
    }

    deinit { if let database { sqlite3_close(database) } }

    /// Terms are generated by the same normalizer as the fallback search;
    /// no user-supplied SQL or FTS operators are admitted.
    func rankedIDs(terms: [String], limit: Int) -> [UUID]? {
        guard !terms.isEmpty, let database else { return [] }
        let expression = terms.map { term in
            "\"\(term.replacingOccurrences(of: "\"", with: "\"\""))\"" + (term.count >= 3 ? "*" : "")
        }.joined(separator: " OR ")
        var statement: OpaquePointer?
        guard sqlite3_prepare_v2(database,
            "SELECT id FROM memories WHERE memories MATCH ? ORDER BY bm25(memories), rowid DESC LIMIT ?",
            -1, &statement, nil) == SQLITE_OK else { return nil }
        defer { sqlite3_finalize(statement) }
        sqlite3_bind_text(statement, 1, expression, -1, transient)
        sqlite3_bind_int(statement, 2, Int32(max(1, min(limit, 256))))
        var result: [UUID] = []
        while true {
            switch sqlite3_step(statement) {
            case SQLITE_ROW:
                if let text = sqlite3_column_text(statement, 0), let id = UUID(uuidString: String(cString: text)) {
                    result.append(id)
                }
            case SQLITE_DONE: return result
            default: return nil
            }
        }
    }
}

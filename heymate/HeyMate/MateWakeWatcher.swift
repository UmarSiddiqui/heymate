//
//  MateWakeWatcher.swift
//  HeyMate
//
//  The Mac-side signals behind agent wakes. Each source runs only while an
//  agent has a wake of that kind turned on, and stops when the last one is
//  removed. Sources report the least they can: a file name, a link, a
//  meeting title, an app name, a sender and subject.
//

import AppKit
import Darwin
import EventKit
import Foundation

@MainActor
final class MateWakeWatcher {
    /// Called on the main actor for every signal a running source produces.
    var onSignal: ((MateWakeSignal) -> Void)?
    /// Whether Calendar and Mail are switched on in Apps right now.
    var calendarAllowed: () -> Bool = { false }
    var mailAllowed: () -> Bool = { false }

    static let clipboardInterval: TimeInterval = 1.5
    static let calendarInterval: TimeInterval = 60
    static let mailInterval: TimeInterval = 15 * 60

    private var activeKinds: Set<MateWakeKind> = []

    // Downloads
    private var downloadsSource: DispatchSourceFileSystemObject?
    private var downloadNames: Set<String>?

    // Clipboard
    private var clipboardTimer: Timer?
    private var clipboardChangeCount = NSPasteboard.general.changeCount
    private static let concealedTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    ]

    // Calendar
    private var calendarTimer: Timer?
    private lazy var eventStore = EKEventStore()

    // Apps
    private var appObserver: NSObjectProtocol?

    // Mail
    private var mailTimer: Timer?
    private var mailKeys: Set<String>?
    private var mailReadInFlight = false

    /// Starts the sources these kinds need and stops the rest.
    func update(kinds: Set<MateWakeKind>) {
        guard kinds != activeKinds else { return }
        activeKinds = kinds
        kinds.contains(.downloadedFile) ? startDownloads() : stopDownloads()
        kinds.contains(.copiedLink) ? startClipboard() : stopClipboard()
        kinds.contains(.meetingSoon) ? startCalendar() : stopCalendar()
        kinds.contains(.appOpened) ? startApps() : stopApps()
        kinds.contains(.newMail) ? startMail() : stopMail()
    }

    func stop() { update(kinds: []) }

    private func emit(_ signal: MateWakeSignal) { onSignal?(signal) }

    // MARK: Downloads

    private var downloadsURL: URL {
        FileManager.default.urls(for: .downloadsDirectory, in: .userDomainMask).first
            ?? FileManager.default.homeDirectoryForCurrentUser.appendingPathComponent("Downloads")
    }

    private func startDownloads() {
        guard downloadsSource == nil else { return }
        let descriptor = open(downloadsURL.path, O_EVTONLY)
        guard descriptor >= 0 else { return }
        let source = DispatchSource.makeFileSystemObjectSource(
            fileDescriptor: descriptor,
            eventMask: [.write, .rename, .delete, .extend],
            queue: DispatchQueue.global(qos: .utility)
        )
        source.setEventHandler { [weak self] in
            Task { @MainActor in self?.downloadsChanged() }
        }
        source.setCancelHandler { close(descriptor) }
        downloadsSource = source
        // The first look is the baseline; only later arrivals are news.
        downloadNames = currentDownloadNames()
        source.resume()
    }

    private func stopDownloads() {
        downloadsSource?.cancel()
        downloadsSource = nil
        downloadNames = nil
    }

    private func currentDownloadNames() -> Set<String>? {
        guard let names = try? FileManager.default.contentsOfDirectory(atPath: downloadsURL.path) else { return nil }
        return Set(names)
    }

    private func downloadsChanged() {
        guard downloadsSource != nil, let current = currentDownloadNames() else { return }
        let fresh = MateWakeDownloads.newlyFinished(previous: downloadNames, current: current)
        downloadNames = current
        let now = Date()
        for name in fresh {
            emit(MateWakeSignal(
                kind: .downloadedFile,
                subject: name,
                fileURL: downloadsURL.appendingPathComponent(name),
                observedAt: now
            ))
        }
    }

    // MARK: Clipboard

    private func startClipboard() {
        guard clipboardTimer == nil else { return }
        clipboardChangeCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: Self.clipboardInterval, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.clipboardTick() }
        }
        RunLoop.main.add(timer, forMode: .common)
        clipboardTimer = timer
    }

    private func stopClipboard() {
        clipboardTimer?.invalidate()
        clipboardTimer = nil
    }

    private func clipboardTick() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != clipboardChangeCount else { return }
        clipboardChangeCount = pasteboard.changeCount
        let types = pasteboard.types ?? []
        // Password managers mark what must not be read; honor that first.
        guard !types.contains(where: Self.concealedTypes.contains) else { return }
        // A copy made inside an app the person excluded is not looked at.
        let front = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        guard !ExcludedApps.isCurrentlyExcluded(bundleId: front) else { return }
        let change = pasteboard.changeCount
        Task { @MainActor [weak self] in
            // macOS can say "this is a web address" without handing over the
            // text. Only then is the copy read, so other text is never seen
            // and the system's paste notice appears for links alone.
            if #available(macOS 15.4, *) {
                guard pasteboard.accessBehavior != .alwaysDeny,
                      let found = try? await pasteboard.detectedPatterns(for: [\.probableWebURL]),
                      found.contains(\.probableWebURL) else { return }
            }
            guard let self, self.clipboardTimer != nil, pasteboard.changeCount == change,
                  let text = pasteboard.string(forType: .string),
                  let link = MateWakeMatcher.link(in: text) else { return }
            self.emit(MateWakeSignal(kind: .copiedLink, subject: link.absoluteString, observedAt: Date()))
        }
    }

    // MARK: Calendar

    private func startCalendar() {
        guard calendarTimer == nil else { return }
        let timer = Timer(timeInterval: Self.calendarInterval, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.calendarTick() }
        }
        RunLoop.main.add(timer, forMode: .common)
        calendarTimer = timer
        calendarTick()
    }

    private func stopCalendar() {
        calendarTimer?.invalidate()
        calendarTimer = nil
    }

    /// Never prompts: without full access already granted this stays quiet.
    private func calendarTick() {
        guard calendarAllowed(), EKEventStore.authorizationStatus(for: .event) == .fullAccess else { return }
        let now = Date()
        let predicate = eventStore.predicateForEvents(
            withStart: now,
            end: now.addingTimeInterval(MateWakeMatcher.meetingLeadTime),
            calendars: nil
        )
        let next = eventStore.events(matching: predicate)
            .filter { !$0.isAllDay && $0.startDate > now }
            .min { $0.startDate < $1.startDate }
        guard let next, let title = next.title, !title.isEmpty else { return }
        emit(MateWakeSignal(
            kind: .meetingSoon,
            subject: title,
            occurrence: String(Int(next.startDate.timeIntervalSince1970)),
            observedAt: now
        ))
    }

    // MARK: Apps

    private func startApps() {
        guard appObserver == nil else { return }
        appObserver = NSWorkspace.shared.notificationCenter.addObserver(
            forName: NSWorkspace.didActivateApplicationNotification, object: nil, queue: .main
        ) { [weak self] notification in
            let app = notification.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication
            guard let name = app?.localizedName, app?.bundleIdentifier != Bundle.main.bundleIdentifier else { return }
            Task { @MainActor in
                self?.emit(MateWakeSignal(kind: .appOpened, subject: name, observedAt: Date()))
            }
        }
    }

    private func stopApps() {
        if let appObserver { NSWorkspace.shared.notificationCenter.removeObserver(appObserver) }
        appObserver = nil
    }

    // MARK: Mail

    private func startMail() {
        guard mailTimer == nil else { return }
        let timer = Timer(timeInterval: Self.mailInterval, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.mailTick() }
        }
        RunLoop.main.add(timer, forMode: .common)
        mailTimer = timer
        mailTick()
    }

    private func stopMail() {
        mailTimer?.invalidate()
        mailTimer = nil
        mailKeys = nil
    }

    /// Reads senders and subjects only, and only while Mail is already
    /// open: asking Mail a question would otherwise launch it.
    private func mailTick() {
        guard mailAllowed(), !mailReadInFlight,
              !NSRunningApplication.runningApplications(withBundleIdentifier: "com.apple.mail").isEmpty else { return }
        mailReadInFlight = true
        Task.detached(priority: .utility) { [weak self] in
            let output = MacAccountContext.mailRawOutput()
            await MainActor.run { self?.mailRead(output) }
        }
    }

    private func mailRead(_ output: String?) {
        mailReadInFlight = false
        guard mailTimer != nil, let output else { return }
        let rows = MateWakeMail.rows(rawOutput: output)
        let fresh = MateWakeMail.newUnread(previousKeys: mailKeys, rows: rows)
        mailKeys = Set(rows.map(\.key))
        let now = Date()
        for row in fresh.prefix(3) {
            emit(MateWakeSignal(kind: .newMail, subject: row.summary, occurrence: row.received, observedAt: now))
        }
    }
}
